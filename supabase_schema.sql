-- 1. جدول المستخدمين (المتسابقين والأدمن)
CREATE TABLE IF NOT EXISTS users (
  id BIGSERIAL PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  full_name TEXT NOT NULL,
  church TEXT,
  phone TEXT,
  password_hash TEXT NOT NULL,
  role TEXT DEFAULT 'contestant', -- 'admin' or 'contestant'
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. جدول الأصحاحات الـ 21
CREATE TABLE IF NOT EXISTS chapters (
  id INT PRIMARY KEY, -- 1 إلى 21
  number INT UNIQUE NOT NULL,
  title TEXT NOT NULL,
  subtitle TEXT,
  text_content TEXT NOT NULL,
  video_url TEXT,
  video_title TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. جدول أسئلة الاختبارات لكل أصحاح
CREATE TABLE IF NOT EXISTS questions (
  id BIGSERIAL PRIMARY KEY,
  chapter_id INT NOT NULL REFERENCES chapters(id) ON DELETE CASCADE,
  question_text TEXT NOT NULL,
  options_json JSONB NOT NULL, -- مصفوفة الخيارات ["خيار 1", "خيار 2", ...]
  correct_index INT NOT NULL, -- مؤشر الإجابة الصحيحة (0, 1, 2, 3)
  explanation TEXT,
  points INT DEFAULT 10
);

-- 4. جدول محاولات ونتائج الاختبارات
CREATE TABLE IF NOT EXISTS quiz_attempts (
  id BIGSERIAL PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  chapter_id INT NOT NULL REFERENCES chapters(id) ON DELETE CASCADE,
  score INT NOT NULL,
  max_score INT NOT NULL,
  time_spent_seconds INT NOT NULL,
  answers_json JSONB,
  completed_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. جدول تقدم المتسابقين وترتيبهم (الدرجات والسرعة)
CREATE TABLE IF NOT EXISTS user_progress (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  last_chapter_id INT DEFAULT 1,
  total_score INT DEFAULT 0,
  total_time_seconds INT DEFAULT 0,
  completed_chapters_count INT DEFAULT 0,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- فهارس لتحسين سرعة لوحة المتصدرين والبحث
CREATE INDEX IF NOT EXISTS idx_progress_ranking ON user_progress (total_score DESC, total_time_seconds ASC);
CREATE INDEX IF NOT EXISTS idx_questions_chapter ON questions (chapter_id);
CREATE INDEX IF NOT EXISTS idx_attempts_user_chapter ON quiz_attempts (user_id, chapter_id);

